"""Render focused cProfile evidence without committing machine-specific binaries."""

import argparse
import pstats
from pathlib import Path


def render(profile_path: Path) -> str:
    """Render useful CPU functions and application frames from a diagnostic run.

    Args:
        profile_path: cProfile binary generated by benchmark --profile.

    Returns:
        Focused markdown with function counts and self time.
    """
    statistics = pstats.Stats(str(profile_path))
    candidates = []
    for (filename, line, function), values in statistics.stats.items():
        if "/backend/" in filename:
            location = "backend/" + filename.split("/backend/", 1)[1]
        elif filename == "~" and any(
            term in function
            for term in (
                "zlib.Compress",
                "BufferedReader",
                "_hashlib.HASH",
                "sqlite3.Connection",
                "strftime",
                "bytes' objects",
            )
        ):
            location = "builtin"
        elif "json/encoder.py" in filename:
            location = "json/encoder.py"
        else:
            continue
        if values[2] >= 0.005:
            candidates.append((values[2], values[1], location, line, function))
    lines = [
        f"Profile: `{profile_path.name}`. Separate diagnostic server lifetime;",
        "these timings are not included in benchmark medians. Self time includes",
        "profiling overhead. Coroutine counts include resumes; threaded/async",
        "cumulative stacks overlap, so cumulative times are deliberately omitted.",
        "",
        "| Function | Location | Calls/resumes | Self seconds |",
        "|---|---|---:|---:|",
    ]
    for self_seconds, calls, location, line, function in sorted(
        candidates, reverse=True
    )[:25]:
        lines.append(
            f"| `{function}` | `{location}:{line}` | {calls} | {self_seconds:.3f} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    """Read a generated profile and write its focused markdown evidence."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profile", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()
    arguments.output.write_text(render(arguments.profile))


if __name__ == "__main__":
    main()
